#!/usr/bin/env node
/**
 * Compute AppSync → CN backend GraphQL operation coverage.
 *
 * Reads the AppSync schema snapshot at ../../scripts/appsync_schema_current.graphql,
 * extracts Query / Mutation / Subscription operation names, then matches each name
 * against the operations declared in index.js (the CN schema).
 *
 * Usage: node scripts/schema-coverage.js
 */

const fs = require('node:fs');
const path = require('node:path');

const APPSYNC_SCHEMA = path.resolve(__dirname, '..', '..', 'scripts', 'appsync_schema_current.graphql');
const CN_INDEX = path.resolve(__dirname, '..', 'index.js');

function extractOps(text, typeName) {
  const lines = text.split('\n');
  const ops = [];
  let inBlock = false;
  let braceDepth = 0;
  for (const raw of lines) {
    const s = raw.trim();
    if (!inBlock) {
      const m = s.match(/^type\s+(\w+)\b/);
      if (m && m[1] === typeName) {
        inBlock = true;
        braceDepth = (raw.match(/\{/g) || []).length - (raw.match(/\}/g) || []).length;
        continue;
      }
    } else {
      braceDepth += (raw.match(/\{/g) || []).length - (raw.match(/\}/g) || []).length;
      if (braceDepth <= 0) break;
      const m = s.match(/^(\w+)\s*(?:\(|:)/);
      if (m) ops.push(m[1]);
    }
  }
  return ops;
}

function extractCnOps(text) {
  const names = new Set();
  for (const typeName of ['Query', 'Mutation', 'Subscription']) {
    const re = new RegExp(`type\\s+${typeName}\\s*\\{([\\s\\S]*?)\\n\\}`, 'g');
    const m = text.match(re);
    if (!m) continue;
    for (const block of m) {
      const body = block.split('\n').slice(1, -1).join('\n');
      for (const line of body.split('\n')) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const match = trimmed.match(/^(\w+)\s*(?:\(|:)/);
        if (match) names.add(match[1]);
      }
    }
  }
  return names;
}

const schema = fs.readFileSync(APPSYNC_SCHEMA, 'utf8');
const cnIndex = fs.readFileSync(CN_INDEX, 'utf8');

const cnOps = extractCnOps(cnIndex);
const summary = {};
for (const typeName of ['Query', 'Mutation', 'Subscription']) {
  const appsyncOps = extractOps(schema, typeName);
  const matched = appsyncOps.filter((op) => cnOps.has(op));
  summary[typeName] = {
    appsync: appsyncOps,
    matched,
    appsyncTotal: appsyncOps.length,
    matchedTotal: matched.length,
  };
}

const md = [];
md.push('# CN TCB backend gap report');
md.push('');
md.push('Auto-generated by `cloudbase-graphql/scripts/schema-coverage.js`.');
md.push('');
md.push('| API type | Matching AppSync operations | AppSync total | Coverage |');
md.push('|---|---:|---:|---:|');
for (const typeName of ['Query', 'Mutation', 'Subscription']) {
  const row = summary[typeName];
  const coverage = row.appsyncTotal ? Math.round((row.matchedTotal / row.appsyncTotal) * 100) : 0;
  md.push(`| ${typeName} | ${row.matchedTotal} | ${row.appsyncTotal} | ${coverage}% |`);
}
md.push('');
md.push('Missing AppSync operations (CN-only names excluded):');
md.push('');
for (const typeName of ['Query', 'Mutation', 'Subscription']) {
  const row = summary[typeName];
  const missing = row.appsync.filter((op) => !cnOps.has(op));
  if (!missing.length) continue;
  md.push(`### ${typeName}`);
  md.push('');
  md.push(missing.map((op) => `- \`${op}\``).join('\n'));
  md.push('');
}
console.log(md.join('\n'));